export function NotationList() {
  const [done] = useStored<string[]>('notation.done', [])
  return (
    <div className="page">
      <div className="crumbs"><Link to="/theory">{tr('Теория')}</Link></div>
      <h1>{tr('Нотная грамота')}</h1>
      <p className="muted lead-narrow">{tr('Восемь коротких уроков: от нотоносца до того, как ноты складываются в аккорды и мелодию. В каждом — примеры, которые можно послушать, и вопрос для проверки. Закрепить чтение нот — в игре')} <Link to="/ear/keys?g=read">{tr('«Читай ноты»')}</Link>.</p>
      <ol className="lesson-list">
        {LESSONS.map((l, i) => (
          <li key={l.id}>
            <Link to={`/notation/${l.id}`} className="tile">
              <span className="lesson-num">{done.includes(l.id) ? <Check size={16} /> : i + 1}</span>
              <strong>{l.title}</strong>
              <span className="muted small">{l.lead}</span>
            </Link>
          </li>
        ))}
      </ol>
    </div>
  )
}

export function NotationLesson() {
  const { id = '' } = useParams()
  const i = LESSONS.findIndex(l => l.id === id)
  const l = LESSONS[i]
  const [done, setDone] = useStored<string[]>('notation.done', [])
  const [pick, setPick] = useState<number | null>(null)
  if (!l) return <div className="page"><p>{tr('Урок не найден.')} <Link to="/notation">{tr('К урокам')}</Link></p></div>
  const next = LESSONS[i + 1]
  const choose = (k: number) => {
    if (pick != null) return
    setPick(k)
    if (k === l.quiz.answer && !done.includes(l.id)) setDone([...done, l.id])
  }
  return (
    <div className="page article">
      <div className="crumbs"><Link to="/theory">{tr('Теория')}</Link> / <Link to="/notation">{tr('Нотная грамота')}</Link> {tr('· урок')} {i + 1} {tr('из')} {LESSONS.length}</div>
      <h1>{l.title}</h1>
      <p className="lead">{l.lead}</p>
      <div className="article-body">{l.body()}</div>
      <section className="card lesson-quiz" key={l.id}>
        <h2>{tr('Проверь себя')}</h2>
        <p>{l.quiz.q}</p>
        {l.quiz.staff}
        <div className="answers">
          {l.quiz.options.map((o, k) => (
            <button key={o} className={'answer' + (pick == null ? '' : k === l.quiz.answer ? ' right' : k === pick ? ' wrong' : ' dim')} disabled={pick != null} onClick={() => choose(k)}>{o}</button>
          ))}
        </div>
        {pick != null && <p className={'verdict' + (pick === l.quiz.answer ? ' ok-msg' : '')} aria-live="polite">{pick === l.quiz.answer ? tr('Верно! ') : tr('Не совсем. ')}{l.quiz.why}</p>}
        {pick != null && pick !== l.quiz.answer && <button className="textbtn" onClick={() => setPick(null)}>{tr('Попробовать ещё раз')}</button>}
      </section>
      {next ? <Link to={`/notation/${next.id}`} className="card next-art" onClick={() => setPick(null)}><span className="muted small">{tr('Дальше')}</span><strong>{next.title} →</strong></Link>
        : <Link to="/ear/keys?g=read" className="card next-art"><span className="muted small">{tr('Закрепить')}</span><strong>{tr('Игра «Читай ноты» →')}</strong></Link>}
    </div>
  )
}
