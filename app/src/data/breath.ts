export type BreathPhase = {
  label: string
  sec: number
  kind: 'in' | 'hold' | 'out' | 'pulse'
  /** Для pulse: сколько коротких толчков за фазу */
  pulses?: number
}

export type BreathEx = {
  id: string
  title: string
  group: 'base' | 'flow' | 'singing' | 'strelnikova'
  level: 1 | 2 | 3
  goal: string
  how: string[]
  mistakes?: string[]
  /** cycle — таймер по фазам; stopwatch — замер выдоха; longnote — длинная нота с микрофоном */
  type: 'cycle' | 'stopwatch' | 'longnote'
  phases?: BreathPhase[]
  rounds?: number
}

