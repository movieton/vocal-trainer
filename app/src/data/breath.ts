import { tr } from '../lib/i18n'
export type BreathPhase = {
  label: string
  sec: number
  kind: 'in' | 'hold' | 'out' | 'pulse'
  /** Для pulse: сколько коротких толчков за фазу */
  pulses?: number
}

export type BreathEx = {
  id: string
  title: string
  group: 'health' | 'base' | 'flow' | 'singing' | 'strelnikova'
  level: 1 | 2 | 3
  goal: string
  how: string[]
  mistakes?: string[]
  /** cycle — таймер по фазам; stopwatch — замер выдоха; longnote — длинная нота с микрофоном */
  type: 'cycle' | 'stopwatch' | 'longnote' | 'vfe'
  /** Доказательность: И — исследования, Ш — признанная школа, П — практика педагогов, Т — традиция без доказательств */
  evidence: 'И' | 'Ш' | 'П' | 'Т'
  /** Ноты для длинной ноты: в полутонах от «до» рабочей октавы */
  presets?: number[]
  phases?: BreathPhase[]
  rounds?: number
}

